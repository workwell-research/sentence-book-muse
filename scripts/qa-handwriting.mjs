
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base=process.env.QA_BASE_URL||'http://127.0.0.1:5317';
const out='.impeccable/review';
await fs.mkdir(out,{recursive:true});
await fs.mkdir('output/pdf',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[],results=[];
try{
 const context=await browser.newContext({viewport:{width:1440,height:1040}});
 await context.addInitScript(()=>localStorage.setItem('sentence-book-muse:composer:v1','do-not-replace-fixture'));
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 await page.locator('[data-testid="pen"]').waitFor();
 const initial=await page.locator('[data-testid="pen"]').getAttribute('transform');
 await page.waitForTimeout(1200);
 assert.notEqual(await page.locator('[data-testid="pen"]').getAttribute('transform'),initial);
 await page.getByRole('button',{name:'一時停止',exact:true}).click();
 const stopped=await page.locator('[data-testid="pen"]').getAttribute('transform');
 await page.waitForTimeout(150);
 assert.equal(await page.locator('[data-testid="pen"]').getAttribute('transform'),stopped);
 assert.ok(await page.locator('path[data-phase="writing"]').evaluateAll(paths=>paths.some(p=>Number(p.getAttribute('stroke-dashoffset'))>0)));
 await page.screenshot({path:out+'/desktop-writing.png',fullPage:true});
 await page.getByLabel('今日、大切にしたいことは？').fill('I make time for a quiet morning.');
 await page.locator('[data-testid="personal-pen"]').waitFor();
 await page.waitForTimeout(100);
 await page.getByRole('button',{name:'筆記を一時停止',exact:true}).click();
 const personalState=await page.locator('[data-testid="personal-strokes"] path').evaluateAll(paths=>paths.map(p=>({offset:Number(p.getAttribute('stroke-dashoffset')),length:Number(p.getAttribute('stroke-dasharray').split(' ')[0])})));
 assert.ok(personalState.some(s=>s.offset===s.length));
 assert.ok(personalState.filter(s=>s.offset>0&&s.offset<s.length).length<=1);
 await page.screenshot({path:out+'/desktop-personal.png',fullPage:true});
 await page.getByRole('button',{name:'筆記を続ける',exact:true}).click();
 await page.locator('[data-testid="personal-pen"]').waitFor();
 await page.getByRole('button',{name:'書き終える',exact:true}).click();
 assert.equal(await page.locator('[data-testid="personal-pen"]').count(),0);
 await page.getByLabel('筆記の速さ').selectOption('4');
 await page.getByRole('button',{name:'続きを見る',exact:true}).click();
 // Export before completion proves that animation state does not limit the printed page.
 const download=page.waitForEvent('download',{timeout:20000});
 await page.getByRole('button',{name:'完成ページをPDFに',exact:true}).click();
 await (await download).saveAs('output/pdf/handwriting-note.pdf');
 await page.getByRole('button',{name:'完成を見る',exact:true}).click();
 assert.equal(await page.locator('svg.notebook').getAttribute('data-complete'),'true');
 assert.equal(await page.locator('[data-testid="pen"]').count(),0);
 assert.ok(await page.locator('path[data-phase]').evaluateAll(paths=>paths.every(p=>Number(p.getAttribute('stroke-dashoffset'))===0)));
 await page.evaluate(()=>document.activeElement?.blur());
 await page.screenshot({path:out+'/desktop.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.equal(await page.evaluate(()=>localStorage.getItem('sentence-book-muse:composer:v1')),'do-not-replace-fixture');
 await page.getByLabel('今日、大切にしたいことは？').fill('日本語');
 assert.equal(await page.getByRole('button',{name:'完成ページをPDFに',exact:true}).isDisabled(),true);
 await page.locator('#personal-error').waitFor();
 assert.equal(await page.getByLabel('今日、大切にしたいことは？').inputValue(),'日本語');
 await page.getByLabel('今日、大切にしたいことは？').fill('');
 await page.getByRole('button',{name:'もう一度見る',exact:true}).click();
 await page.locator('[data-testid="pen"]').waitFor();
 results.push('Desktop: moving pen, pause/resume, speed, completion/replay, typing, unsupported input, PDF before completion, storage preservation and no overflow passed.');
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const phone=await mobile.newPage();phone.on('pageerror',e=>errors.push(e.message));
 await phone.goto(base);
 const skip=phone.getByRole('button',{name:'完成を見る',exact:true});
 assert.ok((await skip.boundingBox()).y<844);
 await skip.click();
 await phone.getByLabel('今日、大切にしたいことは？').fill('A warm cup. A new page.');
 await phone.getByRole('button',{name:'書き終える',exact:true}).click();
 await phone.evaluate(()=>{document.activeElement?.blur();scrollTo(0,0)});
 await phone.screenshot({path:out+'/mobile.png',fullPage:true});
 assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 results.push('Mobile Chrome simulation 390x844: controls in first viewport, complete page, personal input and no overflow passed.');
 results.push('Personal text: pasted input draws one stroke at a time, pen follows, pause/resume and finish work; complete captures include the full personal line.');
 const reduce=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
 const quiet=await reduce.newPage();
 await quiet.goto(base);
 await quiet.waitForFunction(()=>document.querySelector('svg.notebook')?.getAttribute('data-complete')==='true');
 assert.equal(await quiet.locator('[data-testid="pen"]').count(),0);
 await quiet.keyboard.press('Tab');
 assert.equal(await quiet.evaluate(()=>document.activeElement?.textContent),'操作へ移動');
 results.push('Reduced motion shows completed text; keyboard skip link is reachable.');
 assert.deepEqual(errors,[]);
 await fs.writeFile(out+'/results.json',JSON.stringify({results,errors},null,2));
 console.log(JSON.stringify({results,errors},null,2));
}finally{await browser.close();}
