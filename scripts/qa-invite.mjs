import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const origin = process.env.QA_ORIGIN || 'http://127.0.0.1:8801';
if (!['127.0.0.1', 'localhost'].includes(new URL(origin).hostname)) throw new Error('Disposable local origins only.');
const code = 'only-a-test-invitation-not-for-production';
const out = process.env.QA_OUTPUT_DIR || '/private/tmp/sentence-book-invite-qa';
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [], results = [];
const lookup = { expression: 'hello', sentence: 'Say hello.', level: 'A2', native_language: 'ja' };
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin + '/setup');
  await page.getByRole('checkbox', { name: '旅行・お出かけ', exact: true }).check();
  await page.getByRole('button', { name: '関心を保存して進む' }).click();
  await page.getByLabel('話したいこと', { exact: true }).fill('Disposable note stays here.');
  await page.getByRole('button', { name: 'メモを保存', exact: true }).click();
  await page.getByLabel('招待コード', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '教材を作る', exact: true }).isDisabled(), true);
  assert.equal(await page.evaluate(async data => (await fetch('/api/lookup', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(data)})).status, lookup), 401);
  await page.locator('.generation-note').screenshot({ path: out + '/setup-locked.png' });
  await page.getByLabel('招待コード', { exact: true }).fill('wrong');
  await page.getByLabel('招待コード', { exact: true }).press('Enter');
  await page.getByRole('alert').filter({ hasText: '招待コードが一致しません' }).waitFor();
  assert.equal(await page.getByLabel('話したいこと', { exact: true }).inputValue(), 'Disposable note stays here.');
  await page.getByLabel('招待コード', { exact: true }).fill(code);
  await page.getByLabel('招待コード', { exact: true }).press('Enter');
  await page.getByText('招待コードを確認済み', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '教材を作る', exact: true }).isEnabled(), true);
  const cookies = await context.cookies();
  assert.equal(cookies.find(c => c.name === 'sentence-book-access-local')?.httpOnly, true);
  assert.equal(await page.evaluate(() => document.cookie.includes('sentence-book-access')), false);
  assert.equal(await page.evaluate(() => JSON.stringify(localStorage).includes('only-a-test-invitation')), false);
  await page.reload(); await page.getByText('招待コードを確認済み', { exact: true }).waitFor();
  await page.getByRole('button', { name: '教材を作る', exact: true }).click();
  await page.getByRole('heading', { name: 'A Quiet Morning', exact: true }).waitFor();
  const beforeLogout = await page.evaluate(() => JSON.stringify(localStorage));
  await page.getByRole('button', { name: 'このブラウザでの利用を終了', exact: true }).click();
  await page.getByLabel('招待コード', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => JSON.stringify(localStorage)), beforeLogout);
  assert.equal(await page.evaluate(async data => (await fetch('/api/lookup', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(data)})).status, lookup), 401);
  results.push('Anonymous 401; wrong invitation; Enter unlock; HttpOnly/no JS or storage token; reload persistence; authorized generation via mock; logout preserves all local data.');
  await page.goto(origin + '/?page=sample');
  const editor = page.locator('#notebook-input'); await editor.waitFor();
  await page.waitForFunction(() => !document.querySelector('#notebook-input').disabled);
  await editor.fill('Today, I decided to slow down.'); await editor.press('Enter');
  await page.locator('.word-hit').first().click();
  await page.getByLabel('招待コード', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', {name:'調べて線を引く',exact:true}).isDisabled(), true);
  await page.locator('.writing-controls').screenshot({ path: out + '/desk-locked.png' });
  await page.getByLabel('招待コード', { exact: true }).fill(code);
  await page.getByRole('button', { name: 'コードを確認する', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.lookup-button').disabled);
  await page.getByRole('button', { name: '調べて線を引く', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('sentence-book-muse:sample-copy:v1')).lookups.length === 1);
  await page.locator('.word-hit').first().click();
  await context.clearCookies(); // This browser context contains only disposable fixtures.
  await page.getByRole('button', { name: '調べて線を引く', exact: true }).click();
  await page.getByLabel('招待コード', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('sentence-book-muse:sample-copy:v1')).entries.length), 1);
  results.push('Public Copy works while locked; selected phrase survives unlock; authorized lookup via mock; expired session returns to code input without losing progress.');
  await page.getByRole('button',{name:'表示・印刷',exact:true}).click();
  await page.locator('input[name=desk-theme][value="walnut"]').check();
  await page.getByRole('button',{name:'閉じる',exact:true}).click();
  await page.locator('.writing-controls').screenshot({ path: out + '/desk-walnut-locked.png' });
  const mobile = await browser.newContext({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true });
  const phone = await mobile.newPage(); phone.on('pageerror', e => errors.push(e.message));
  await phone.goto(origin + '/setup');
  await phone.getByRole('button', { name: 'あとで選ぶ', exact: true }).click();
  await phone.getByLabel('招待コード', { exact: true }).waitFor();
  await phone.locator('.generation-note').screenshot({ path: out + '/mobile-locked.png' });
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await phone.getByLabel('招待コード', { exact: true }).evaluate(el => getComputedStyle(el).fontSize), '16px');
  await phone.route('**/api/access', route => route.abort());
  await phone.getByLabel('招待コード', { exact: true }).fill(code);
  await phone.getByRole('button', { name: 'コードを確認する', exact: true }).click();
  await phone.getByRole('alert').filter({ hasText: '通信できませんでした' }).waitFor();
  assert.equal(await phone.getByLabel('招待コード', { exact: true }).inputValue(), code);
  results.push('375px layout without overflow, 16px code input, offline feedback retains the entered code.');
  assert.deepEqual(errors, []);
  await fs.writeFile(out + '/results.json', JSON.stringify({ results, errors }, null, 2));
  console.log(JSON.stringify({ results, errors, out }, null, 2));
} finally { await browser.close(); }
